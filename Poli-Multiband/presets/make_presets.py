#!/usr/bin/env python3
"""presets/factory.json -> src/presets.h (the engine's table), the "preset" parameter's option list in vst/params.json,
and PRESETS.md (the list with every value). build.sh runs this before the build; edit factory.json (or spec.py and re-run
tune.py) to change a preset.

The "preset" parameter is appended at the end of params.json (projects store values by position) and vst.json's
"programs": {"param": "preset"} makes the toolchain's wrapper list its options in MPC's PRESET menu.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
KEYS = ("input", "out", "thr", "att", "rel", "knee", "ratio", "uthr", "uratio")
LIMITS = dict(input=(-24, 24), out=(-24, 24), thr=(-60, 0), att=(0.1, 100), rel=(5, 2000), knee=(0, 24), ratio=(1, 20),
              uthr=(-60, 0), uratio=(1, 10))


def fmt_freq(f):
    if f < 999.5:
        return "%d hz" % round(f)
    k = "%.1f" % (f / 1000)
    return (k[:-2] if k.endswith(".0") else k) + "k"


def cf(v):   # a C float literal: 500 -> 500.0f
    s = "%g" % v
    return (s if ("." in s or "e" in s) else s + ".0") + "f"


def num(v):
    s = "%.1f" % v
    return s[:-2] if s.endswith(".0") else s


def main():
    presets = json.load(open(os.path.join(HERE, "factory.json")))["presets"]
    names = [p["name"] for p in presets]
    assert len(set(names)) == len(names), "duplicate preset names"
    for p in presets:
        assert len(p["name"]) <= 23, "too long for MPC's PRESET menu: %r" % p["name"]
        assert all(c.isascii() and c != '"' for c in p["name"]), p["name"]
        assert 20 <= p["x1"] and p["x1"] * 1.25 <= p["x2"] <= 20000, "%s: crossovers" % p["name"]
        for b in p["bands"]:
            for k in KEYS:
                lo, hi = LIMITS[k]
                assert lo <= b[k] <= hi, "%s: %s=%s outside %s..%s" % (p["name"], k, b[k], lo, hi)
            assert b["uthr"] <= b["thr"], "%s: upward thresh above comp thresh" % p["name"]

    # src/presets.h
    rows = []
    for p in presets:
        bands = ", ".join("{%s}" % ", ".join(cf(b[k]) for k in KEYS) for b in p["bands"])
        rows.append('    {"%s", %s, %s, {%s}},' % (p["name"], cf(p["x1"]), cf(p["x2"]), bands))
    h = ["// Generated by presets/make_presets.py from presets/factory.json -- edit those, not this.",
         "// Per band: input, output, thresh (dB), attack, release (ms), knee (dB), ratio, upward thresh (dB), upward ratio.",
         "#pragma once",
         "struct PresetBand { float input, output, thresh, attack, release, knee, ratio, upThresh, upRatio; };",
         "struct Preset { const char *name; float x1, x2; PresetBand band[3]; };",
         "static const Preset kPresets[] = {", *rows, "};",
         "static const int kNumPresets = %d;" % len(presets), ""]
    with open(os.path.join(ROOT, "src", "presets.h"), "w", newline="\n") as f:
        f.write("\n".join(h))

    # vst/params.json: the "preset" parameter, last
    pj = os.path.join(ROOT, "vst", "params.json")
    d = json.load(open(pj))
    ps = [q for q in d["params"] if q["key"] == "preset"]
    entry = {"key": "preset", "name": "Preset", "options": names, "default": 0}
    if ps:
        ps[0].update(entry)
    else:
        d["params"].append(entry)
    # append-only: "preset" stays where it is (index 20); the on-screen selector's parameters come after it
    # (../shared/poli_preset_ui.py, run by generate_skin.py)
    assert [q["key"] for q in d["params"]].index("preset") == 20, "preset must stay parameter 20"
    with open(pj, "w", newline="\n") as f:
        f.write(json.dumps(d, indent=1) + "\n")

    # PRESETS.md
    md = ["# Poli-Multiband factory presets", "",
          "Pick them from the **PRESET** menu at the top of the plugin's screen on the MPC. Generated by "
          "`presets/make_presets.py` from `presets/factory.json`.", "",
          "The presets were tuned on reference audio (presets/README.md): vocals peaking at -3 dBFS, a drum loop at "
          "-1 dBFS, finished mixes at their own level. If your track is much quieter or louder, move each band's "
          "**Thresh** so the green meter goes past the white bar about as much as described below. "
          "*Level* = how much louder or quieter than the dry signal the preset played on its reference.", ""]
    cat = None
    for i, p in enumerate(presets):
        if p["cat"] != cat:
            cat = p["cat"]
            md += ["## %s" % {"Init": "Start", "Vocal": "Vocals", "Mix": "Mix bus", "Master": "Mastering"}.get(cat, cat), ""]
        m = p.get("measured")
        level = ""
        if m:
            level = " Level %s dB on %s." % (num(m["rms_out"] - m["rms_in"]), p.get("measured_on", ""))
        md += ["### %d. %s" % (i, p["name"]), "", p["about"] + level, "",
               "Split: %s / %s" % (fmt_freq(p["x1"]), fmt_freq(p["x2"])), "",
               "| Band | Input | Output | Thresh | Attack | Release | Knee | Ratio | Up Thresh | Up Ratio | Measured |",
               "|---|---|---|---|---|---|---|---|---|---|---|"]
        rng = ["20 hz-%s" % fmt_freq(p["x1"]), "%s-%s" % (fmt_freq(p["x1"]), fmt_freq(p["x2"])), "%s-20k" % fmt_freq(p["x2"])]
        for j, b in enumerate(p["bands"]):
            meas = ""
            if m:
                mb = m["bands"][j]
                parts = []
                if mb["down_p90"] >= 0.3:
                    parts.append("-%s dB" % num(mb["down_p90"]))
                if mb["up_p90"] >= 0.3:
                    parts.append("+%s dB up" % num(mb["up_p90"]))
                meas = ", ".join(parts) or "-"
            up = "%s:1" % num(b["uratio"]) if b["uratio"] > 1 else "off"
            md.append("| %d (%s) | %s db | %s db | %s db | %s ms | %s ms | %s db | %s:1 | %s | %s | %s |" % (
                j + 1, rng[j], num(b["input"]), num(b["out"]), num(b["thr"]), num(b["att"]), num(b["rel"]), num(b["knee"]),
                num(b["ratio"]), "%s db" % num(b["uthr"]) if b["uratio"] > 1 else "-", up, meas))
        md.append("")
    md += ["*Measured*: gain reduction (and upward boost) on the reference audio, 90th percentile while the band plays, "
           "about what a gain-reduction meter shows on the loud parts. The de-essers' numbers are the 90th percentile "
           "of the whole top band; on the esses themselves they take off about 8 dB.", ""]
    with open(os.path.join(ROOT, "PRESETS.md"), "w", newline="\n") as f:
        f.write("\n".join(md))
    print("presets: %d -> src/presets.h, vst/params.json (preset), PRESETS.md" % len(presets))


if __name__ == "__main__":
    main()
