#!/usr/bin/env python3
"""Writes vst/params.json: every Poli-Juicebox parameter, in VST index order (append only: projects store values by position).

Knobs are positions 0..1000 (the engine maps them to semitones / Hz / dB / %; "dynamic_display" shows the real value under the knob).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "presets"))
import factory  # noqa: E402

NAMES = {"pitch": "Pitch", "formant": "Formant", "ftrack": "F-Track", "thresh": "Threshold", "lowend": "Low end", "attack": "Attack",
         "release": "Release", "odd": "Odd drive", "even": "Even drive", "color": "Color", "f1c": "F1 Freq", "f1q": "F1 Q",
         "f2c": "F2 Freq", "f2q": "F2 Q", "f3c": "F3 Freq", "f3q": "F3 Q", "fsmooth": "F-Smooth", "air": "Air", "natural": "Natural",
         "mix": "Mix", "hold": "Hold", "rasp": "Rasp", "glide": "Glide", "guard": "Oct guard", "morph": "Morph", "floor": "Floor",
         "ceil": "Ceiling", "overlap": "Overlap"}
PAGES = ["Shape", "Tone", "Filter", "Tracking"]
# The 16 Q-Links ql01..ql16 (4 columns = 4 Q-Link pages on the MPC). Column 1 is the Smoothen panel on every page; columns 2-4 follow the
# page on show (the tab pressed). "" = nothing on that slot. generate_skin.py draws the numbered dots from these tables and the engine
# reads them from src/qlinks_gen.h, so the picture and the behaviour cannot disagree.
QLEFT = ["fsmooth", "air", "natural", "mix"]
QPAGES = [   # per page: columns 2, 3, 4 (4 keys each)
    ["pitch", "formant", "ftrack", "link", "", "", "", "", "", "", "", ""],
    ["thresh", "lowend", "attack", "release", "odd", "even", "color", "", "", "", "", ""],
    ["f1c", "f2c", "f3c", "", "f1q", "f2q", "f3q", "", "", "", "", ""],
    ["floor", "ceil", "glide", "guard", "rasp", "hold", "morph", "overlap", "", "", "", ""],
]
QNAMES = dict(NAMES, link="P&F Link")


def qslots(page):
    return QLEFT + QPAGES[page]


def write_qlinks_header():
    L = ["// Generated by make_params.py (QLEFT / QPAGES): which knob each Q-Link slot drives on each page. Do not edit.",
         "static const int kQPages = %d;" % len(PAGES),
         "static const char *const kQKey[%d][16] = {" % len(PAGES)]
    for pg in range(len(PAGES)):
        L.append("    {" + ", ".join('"%s"' % k for k in qslots(pg)) + "},")
    L += ["};", "static const char *const kQName[%d][16] = {" % len(PAGES)]
    for pg in range(len(PAGES)):
        L.append("    {" + ", ".join('"%s"' % (QNAMES[k] if k else "-") for k in qslots(pg)) + "},")
    L.append("};")
    with open(os.path.join(HERE, "src", "qlinks_gen.h"), "w", newline="\n") as f:
        f.write("\n".join(L) + "\n")


def mom(key, name):
    return {"key": key, "name": name, "min": 0.0, "max": 1.0, "default": 0.0, "momentary": True}


def views():
    """(category, page) for every browser view, in the order juice_nav.h numbers them."""
    out = []
    for c, name in enumerate(factory.CAT_NAMES):
        n = len(factory.PRESETS) if c == 0 else sum(1 for d in factory.PRESETS if d["cat"] == name)
        for p in range(max(1, (n + 11) // 12)):
            out.append((c, p))
    return out


def build():
    names = [factory.menu_name(d) for d in factory.PRESETS]
    P = []
    for k, d in zip(factory.KEYS, factory.DEFAULT_POS):
        P.append({"key": k, "name": NAMES[k], "min": 0.0, "max": 1000.0, "default": float(d), "dynamic_display": True})
    P.append({"key": "link", "name": "P&F Link", "options": ["Off", "Variable"], "default": 0, "refresh_display": True, "qlink_ticks": 4})
    # the right-hand page (engine-owned, set by the tab buttons; the skin shows one page of knobs with when=page:...)
    P += [{"key": "page", "name": "Page", "options": PAGES, "default": 0, "live": True}] + \
         [mom("tab%d" % (i + 1), "Tab %d" % (i + 1)) for i in range(2)]   # tab3 / tab4 are appended at the end (params.lock)
    # the preset selector and browser (juice_nav.h)
    P += [{"key": "preset", "name": "Preset", "options": names, "default": 0, "refresh_display": True, "qlink_ticks": 2},
          mom("preset_prev", "Preset <"), mom("preset_next", "Preset >"), mom("preset_list", "Preset list"),
          {"key": "browsing", "name": "Browsing", "options": ["Off", "On"], "default": 0, "live": True},
          {"key": "bview", "name": "Browser view", "options": ["Closed"] + ["v%d" % (i + 1) for i in range(len(views()))],
           "default": 0, "live": True},
          {"key": "pre_hl", "name": "Preset shown", "options": ["-"] + [str(i + 1) for i in range(12)], "default": 0,
           "live": True},
          mom("bpage_prev", "Page <"), mom("bpage_next", "Page >")]
    P += [mom("cat%d" % (i + 1), "Category %d" % (i + 1)) for i in range(len(factory.CAT_NAMES))]
    P += [mom("pick%d" % (i + 1), "Pick %d" % (i + 1)) for i in range(12)]
    # the help window (appended last: parameter indices of earlier versions stay put)
    P += [mom("help_btn", "Help"), mom("help_next", "Help page"),
          {"key": "hview", "name": "Help view", "options": ["Closed", "Help 1", "Help 2"], "default": 0, "live": True}]
    # the latency pills (Tracking page footer): 0 off the Tracking page, else 1 + mode (Fast / Balanced / Smooth)
    P += [mom("lat1", "Latency Fast"), mom("lat2", "Latency Balanced"), mom("lat3", "Latency Smooth"),
          {"key": "lview", "name": "Latency view", "options": ["Hidden", "Fast", "Balanced", "Smooth"], "default": 0, "live": True}]
    # Learn (header button): on = listening (switches itself off when it has heard enough); learn_prog is its progress bar
    P += [{"key": "learn", "name": "Learn", "options": ["Off", "On"], "default": 0, "refresh_display": True, "live": True},
          {"key": "learn_prog", "name": "Learn progress", "min": 0.0, "max": 1.0, "default": 0.0, "live": True}]
    # (1.5.0) the other two page tabs, and the Q-Link proxies: ql01..ql16 drive whatever knob qlinks_gen.h puts on that slot for the page on show
    P += [mom("tab3", "Tab 3"), mom("tab4", "Tab 4")]
    for i in range(16):
        P.append({"key": "ql%02d" % (i + 1), "name": "Q-Link %d.%d" % (i // 4 + 1, i % 4 + 1), "min": 0.0, "max": 1000.0, "default": 0.0,
                  "dynamic_display": True, "dynamic_name": True})
    return {"name": "Poli-Juicebox", "params": P}


def main():
    path = os.path.join(HERE, "vst", "params.json")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n") as f:
        json.dump(build(), f, indent=1)
        f.write("\n")
    write_qlinks_header()
    print("params: %d, browser views: %d" % (len(build()["params"]), len(views())))


if __name__ == "__main__":
    main()
