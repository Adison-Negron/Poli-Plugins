#!/usr/bin/env python3
"""Designs the two polyphase all-pass half-band IIR filters used by SatDSP's 4x oversampler and prints src/halfband.h.

H(z) = 1/2 [A0(z^2) + z^-1 A1(z^2)],  A(z^2) = prod (a_k + z^-2) / (1 + a_k z^-2)
Poles of an elliptic half-band low-pass lie on the imaginary axis (z = +-j r_k), so a_k = r_k^2. The two branches alternate
the coefficients in increasing order. Stage 1 (44.1 -> 88.2 kHz) is steep (pass to 19.8 kHz, stop from 24.3 kHz); stage 2
(88.2 -> 176.4 kHz) only has to separate 22 kHz from 66 kHz.

    python3 tools/design_halfband.py > src/halfband.h
"""
import sys
import numpy as np
from scipy import signal


def design(order, wp):
    """elliptic half-band of odd `order`, passband edge wp (fraction of the output Nyquist) -> sorted a_k (r^2 of the pole pairs)"""
    # half-band condition: stopband ripple fixed by the passband ripple; pick the passband ripple that gives the best attenuation
    best = None
    for rp_db in np.logspace(-12, -3, 200):
        rs_db = -10 * np.log10(1 - 10 ** (-rp_db / 10))
        try:
            z, p, k = signal.ellip(order, rp_db, rs_db, wp, output="zpk")
        except Exception:
            continue
        # check pole structure: on the imaginary axis in the z-plane? (half-band condition satisfied)
        pr = np.abs(p[np.abs(p.imag) > 1e-9])
        if len(pr) == 0:
            continue
        off = np.max(np.abs(p.real))
        if best is None or off < best[0]:
            best = (off, rp_db, rs_db, p)
    return best


def a_from_poles(p):
    r = np.sort(np.abs(p[p.imag > 1e-9]))
    return r ** 2


def response(a, n=4096):
    a = np.sort(np.asarray(a))
    a0, a1 = a[0::2], a[1::2]       # branches alternate
    w = np.linspace(0, np.pi, n)
    z2 = np.exp(-2j * w)
    A0 = np.ones_like(z2)
    for c in a0:
        A0 *= (c + z2) / (1 + c * z2)
    A1 = np.ones_like(z2)
    for c in a1:
        A1 *= (c + z2) / (1 + c * z2)
    H = 0.5 * (A0 + np.exp(-1j * w) * A1)
    return w / (2 * np.pi), H      # frequency as a fraction of the OUTPUT rate


def try_order(order, fp):
    """fp = passband edge as a fraction of the output rate; halfband symmetric about 0.25"""
    wp = fp / 0.5
    b = design(order, wp)
    return b


if __name__ == "__main__" and len(sys.argv) > 1:      # --table: print the design study
    for order, fp in ((9, 0.2), (11, 0.22), (13, 0.225), (15, 0.2268), (5, 0.125), (7, 0.125)):
        b = try_order(order, fp)
        if b is None:
            print(order, fp, "no design")
            continue
        off, rp, rs, p = b
        a = a_from_poles(p)
        f, H = response(a)
        att = -20 * np.log10(np.max(np.abs(H[f >= 0.5 - fp])) + 1e-30)
        pb = 20 * np.log10(np.abs(H[f <= fp]))
        print("order", order, "fp", fp, "pole off-axis", off, "rs", round(rs, 1), "a", np.round(a, 6), "stop att %.1f dB" % att,
              "pass ripple %.5f dB" % (pb.max() - pb.min()))


def emit():
    out = ["// Generated by tools/design_halfband.py -- polyphase all-pass half-band filters for the 4x oversampler.",
           "// Coefficients are sorted ascending; the even-numbered ones form branch 0, the odd-numbered ones branch 1.",
           "#pragma once", "namespace sat {"]
    for name, order, fp in (("kHb1", 13, 0.225), ("kHb2", 7, 0.125)):
        off, rp, rs, p = design(order, fp / 0.5)
        a = np.sort(a_from_poles(p))
        f, H = response(a)
        att = -20 * np.log10(np.max(np.abs(H[f >= 0.5 - fp])))
        out.append("// order %d, passband edge %.3f of the output rate, stopband attenuation %.1f dB" % (order, fp, att))
        out.append("static const int %sN = %d;" % (name, len(a)))
        out.append("static const float %s[%d] = {%s};" % (name, len(a), ", ".join("%.9ff" % v for v in a)))
    out.append("}  // namespace sat")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__" and len(sys.argv) == 1:
    emit()
